const uint8_t *font_get_glyph(uint32_t character) {
    if (character == 'A')
        return font_glyph_a;
    if (character == 'B')
        return font_glyph_b;
    if (character == 'C')
        return font_glyph_c;
    if (character == 'D')
        return font_glyph_d;
    if (character == 'E')
        return font_glyph_e;
    if (character == 'F')
        return font_glyph_f;
    if (character == 'G')
        return font_glyph_g;
    if (character == 'H')
        return font_glyph_h;
    if (character == 'I')
        return font_glyph_i;
    if (character == 'J')
        return font_glyph_j;
    if (character == 'K')
        return font_glyph_k;
    if (character == 'L')
        return font_glyph_l;
    if (character == 'M')
        return font_glyph_m;
    if (character == 'N')
        return font_glyph_n;
    if (character == 'O')
        return font_glyph_o;
    if (character == 'P')
        return font_glyph_p;
    if (character == 'Q')
        return font_glyph_q;
    if (character == 'R')
        return font_glyph_r;
    if (character == 'S')
        return font_glyph_s;
    if (character == 'T')
        return font_glyph_t;
    if (character == 'U')
        return font_glyph_u;
    if (character == 'V')
        return font_glyph_v;
    if (character == 'W')
        return font_glyph_w;
    if (character == 'X')
        return font_glyph_x;
    if (character == 'Y')
        return font_glyph_y;
    if (character == 'Z')
        return font_glyph_z;
    if (character == '0')
        return font_glyph_zero;
    if (character == '1')
        return font_glyph_one;
    if (character == '2')
        return font_glyph_two;
    if (character == '3')
        return font_glyph_three;
    if (character == '4')
        return font_glyph_four;
    if (character == '5')
        return font_glyph_five;
    if (character == '6')
        return font_glyph_six;
    if (character == '7')
        return font_glyph_seven;
    if (character == '8')
        return font_glyph_eight;
    if (character == '9')
        return font_glyph_nine;
    if (character == ' ')
        return font_glyph_space;
    if (character == '.')
        return font_glyph_period;
    if (character == ',')
        return font_glyph_comma;
    if (character == ':')
        return font_glyph_colon;
    if (character == ';')
        return font_glyph_semicolon;
    if (character == '-')
        return font_glyph_minus;
    if (character == '_')
        return font_glyph_underscore;
    if (character == '/')
        return font_glyph_slash;
    if (character == '?')
        return font_glyph_question;
    if (character == '+')
        return font_glyph_plus;
    if (character == '=')
        return font_glyph_equals;
    if (character == '>')
        return font_glyph_greater;
    if (character == '<')
        return font_glyph_less;
    if (character == '!')
        return font_glyph_exclamation;
    if (character == '*')
        return font_glyph_asterisk;

    if (character == 0x00c7 || character == 0x00e7)
        return font_glyph_c_cedilla;
    if (character == 0x011e || character == 0x011f)
        return font_glyph_g_breve;
    if (character == 0x0130)
        return font_glyph_i_dotted;
    if (character == 0x0131)
        return font_glyph_i;
    if (character == 0x00d6 || character == 0x00f6)
        return font_glyph_o_umlaut;
    if (character == 0x015e || character == 0x015f)
        return font_glyph_s_cedilla;
    if (character == 0x00dc || character == 0x00fc)
        return font_glyph_u_umlaut;

    return 0;
}
